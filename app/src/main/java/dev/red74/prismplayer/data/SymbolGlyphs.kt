import java.util.concurrent.ConcurrentHashMap

/**
 * Symbols the TV's own fonts cannot draw but the app's symbol fonts can (Noto Sans Symbols, Symbols 2 and Math,
 * in res/font, OFL licence): the screen shows them as in the list instead of losing them. [pieces] tells which
 * stretches of a text need which bundled font; text the TV draws by itself (nearly all of it) is left alone.
 */
object SymbolGlyphs {
    /** Which bundled font draws a stretch: index into [FONTS]. */
    class Piece(val start: Int, val end: Int, val font: Int)

    /** Whether the TV's own fonts draw a character, set by the app at start (Paint.hasGlyph). Null: they do. */
    @Volatile
    var systemDraws: ((String) -> Boolean)? = null
        set(value) {
            field = value
            system.clear()
        }

    private val system = ConcurrentHashMap<Int, Boolean>()

    /** Bundled font that has [codePoint], or -1. */
    fun fontOf(codePoint: Int): Int {
        if (codePoint < 0x250) return -1
        for (font in FONTS.indices) if (inRanges(FONTS[font], codePoint)) return font
        return -1
    }

    /** Whether the screen can show [codePoint]: the TV's fonts or the bundled ones. */
    fun draws(codePoint: Int): Boolean = drawsOnTv(codePoint) || fontOf(codePoint) >= 0

    /** Stretches of [text] that need a bundled font, or an empty list (the usual case, checked quickly). */
    fun pieces(text: String): List<Piece> {
        if (systemDraws == null) return emptyList()
        var out: ArrayList<Piece>? = null
        var index = 0
        while (index < text.length) {
            val codePoint = text.codePointAt(index)
            val next = index + Character.charCount(codePoint)
            if (codePoint >= 0x250) {
                val font = fontOf(codePoint)
                if (font >= 0 && !drawsOnTv(codePoint)) {
                    val list = out ?: ArrayList<Piece>().also { out = it }
                    val last = list.lastOrNull()
                    if (last != null && last.end == index && last.font == font) {
                        list[list.lastIndex] = Piece(last.start, next, font)
                    } else {
                        list += Piece(index, next, font)
                    }
                }
            }
            index = next
        }
        return out ?: emptyList()
    }

    private fun drawsOnTv(codePoint: Int): Boolean {
        val check = systemDraws ?: return true
        return system.getOrPut(codePoint) { runCatching { check(String(Character.toChars(codePoint))) }.getOrDefault(true) }
    }

    private fun inRanges(ranges: IntArray, codePoint: Int): Boolean {
        var low = 0
        var high = ranges.size / 2 - 1
        while (low <= high) {
            val mid = (low + high) ushr 1
            when {
                codePoint < ranges[mid * 2] -> high = mid - 1
                codePoint > ranges[mid * 2 + 1] -> low = mid + 1
                else -> return true
            }
        }
        return false
    }

